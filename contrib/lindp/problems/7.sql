DO $$
DECLARE
  i int; j int; cols text;
BEGIN
  FOR i IN 1..32 LOOP
    EXECUTE format('DROP TABLE IF EXISTS m%s CASCADE', i);
    cols := '';
    FOR j IN 1..120 LOOP
      cols := cols || format('c%s int,', j);
    END LOOP;
    cols := left(cols, length(cols) - 1);
    EXECUTE format('CREATE TABLE m%s (%s)', i, cols);
    -- A few rows are enough; planning cost, not execution, is what we exercise.
    EXECUTE format('INSERT INTO m%s SELECT %s FROM generate_series(1, 50) g',
                   i, (SELECT string_agg('g', ',') FROM generate_series(1, 120)));
    EXECUTE format('ANALYZE m%s', i);
  END LOOP;
END $$;

